"""Bundle the three trained models into src/models.js for the browser and Node.
Also stores reference predictions so the JavaScript tests can check that the
browser code gives exactly the same numbers as the Python training code."""
import json, os
import numpy as np
import pandas as pd
import forecast as fc

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
f = json.load(open(os.path.join(OUT, "forecast_model.json")))
fraud = json.load(open(os.path.join(OUT, "fraud_model.json")))
prov = json.load(open(os.path.join(OUT, "provider_model.json")))

# reference forecast at "today"
df = pd.read_csv(os.path.join(OUT, "sar_bdt_series.csv"), parse_dates=["date"])
t = int(np.where(df["date"] == fc.TODAY)[0][0])
ref = fc.predict_one(f, df, t)
f["check"] = {"date": str(fc.TODAY.date()), "pred": {str(h): {str(q): v for q, v in d.items()} for h, d in ref.items()}}

# reference fraud score
W1 = np.array(fraud["W1"]); b1 = np.array(fraud["b1"]); W2 = np.array(fraud["W2"]); b2 = fraud["b2"]
mu = np.array(fraud["mu"]); sd = np.array(fraud["sd"])
x = np.array([2.0, 1, 0.35, 0, 0, 0, 1, 1, 0, 1], float); x[0] = np.log(x[0]); x[4] = np.log1p(x[4])
h = np.tanh(((x - mu) / sd) @ W1 + b1)
fraud["check"] = {"features": [2.0, 1, 0.35, 0, 0, 0, 1, 1, 0, 1], "score": float(1 / (1 + np.exp(-(h @ W2 + b2))))}

reports = {k: json.load(open(os.path.join(OUT, f"{k}.json"))) for k in ("forecast_report", "fraud_report_5seeds", "provider_report")}
bundle = {"forecast": f, "fraud": fraud, "provider": {k: v for k, v in prov.items()}, "reports": reports}
js = ("/* Generated by ml/build_models.py - trained models for FinPassport (simulated data). */\n"
      "(function (root) {\n  var MODELS = " + json.dumps(bundle, separators=(",", ":")) + ";\n"
      "  if (typeof module !== 'undefined' && module.exports) module.exports = MODELS; else root.FinPassportModels = MODELS;\n"
      "})(typeof window !== 'undefined' ? window : this);\n")
dst = os.path.join(HERE, "..", "src", "models.js")
open(dst, "w").write(js)
print("wrote", dst, len(js) // 1024, "KB")
